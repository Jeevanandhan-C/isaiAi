/**
 * Helper to get the styles dedicated to a specific language,
 * or global styles if requested.
 */
export function getStylesForLanguage(languageCode: string): MusicStyleOption[] {
  // If specific language is chosen
  const matched = MUSIC_STYLES.filter((s) => s.language === languageCode);
  if (matched.length > 0) {
    return matched;
  }
  // Default to Tamil if not matched
  return MUSIC_STYLES.filter((s) => s.language === 'ta');
}

